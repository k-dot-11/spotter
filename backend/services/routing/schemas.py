"""
Domain Schemas and Data Models for Routing and Spatial Sampling.
"""

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any


@dataclass
class Checkpoint:
    """A sampled checkpoint along a route."""

    index: int
    lat: float
    lon: float
    distance_from_start_miles: float
    segment_miles: float
    eta: datetime
    eta_iso: str
    elapsed_seconds: float

    def to_dict(self) -> dict[str, Any]:
        return {
            "index": self.index,
            "lat": round(self.lat, 5),
            "lon": round(self.lon, 5),
            "distance_from_start_miles": round(self.distance_from_start_miles, 1),
            "segment_miles": round(self.segment_miles, 1),
            "eta_iso": self.eta_iso,
            "elapsed_seconds": round(self.elapsed_seconds, 1),
        }


@dataclass
class RawRoute:
    """A raw route option generated by a routing provider before weather analysis."""

    route_id: str
    name: str
    summary: str
    distance_miles: float
    duration_seconds: float
    geometry_coordinates: list[tuple[float, float]]  # List of (lon, lat)
    checkpoints: list[Checkpoint] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "route_id": self.route_id,
            "name": self.name,
            "summary": self.summary,
            "distance_miles": round(self.distance_miles, 1),
            "duration_seconds": self.duration_seconds,
            "geometry_coordinates": self.geometry_coordinates,
            "checkpoints": [cp.to_dict() for cp in self.checkpoints],
        }
